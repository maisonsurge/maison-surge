// npm run db:types
// Generates src/types/database.types.ts in the same shape as
// `supabase gen types typescript`, by applying the migrations to an in-memory
// Postgres (PGlite) and introspecting the catalog. With a linked Supabase
// project you can alternatively run:
//   npx supabase gen types typescript --project-id <id> --schema public > src/types/database.types.ts
import { writeFileSync } from "node:fs";
import { createDatabase } from "./lib/pglite-db.mjs";

const db = await createDatabase({ seed: false });
const q = async (sql) => (await db.query(sql)).rows;

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`);
const enumNames = new Set(enums.map((e) => e.name));

const columns = await q(`
  select c.relname as table, a.attname as name, a.attnum as pos,
         format_type(a.atttypid, a.atttypmod) as type, t.typname as udt, t.typcategory as cat,
         et.typname as elem_udt, not a.attnotnull as nullable,
         (ad.adbin is not null) as has_default, a.attidentity <> '' as is_identity,
         a.attgenerated <> '' as is_generated
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_type t on t.oid = a.atttypid
  left join pg_type et on et.oid = t.typelem and t.typcategory = 'A'
  left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
  order by c.relname, a.attnum`);

const fks = await q(`
  select con.conname as name, c.relname as table, rc.relname as ref_table, rn.nspname as ref_schema,
    (select array_agg(a.attname order by k.ord) from unnest(con.conkey) with ordinality k(attnum, ord)
       join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum) as cols,
    (select array_agg(a.attname order by k.ord) from unnest(con.confkey) with ordinality k(attnum, ord)
       join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.attnum) as ref_cols,
    exists (select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique and i.indpred is null
            and (select array_agg(x order by x) from unnest(i.indkey::int2[]) x) =
                (select array_agg(x order by x) from unnest(con.conkey) x)) as one_to_one
  from pg_constraint con
  join pg_class c on c.oid = con.conrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_class rc on rc.oid = con.confrelid
  join pg_namespace rn on rn.oid = rc.relnamespace
  where con.contype = 'f' and n.nspname = 'public'
  order by c.relname, con.conname`);

const functions = await q(`
  select p.proname as name, p.proretset as retset, p.prorettype::regtype::text as rettype,
    rt.typname as ret_udt, rt.typtype as ret_typtype,
    coalesce(p.proargnames, '{}') as argnames, coalesce(p.proargmodes::text[], '{}') as argmodes,
    (select array_agg(format_type(x, null) order by ord) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(x, ord)) as argtypes,
    (select array_agg(t.typname order by ord) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(x, ord) join pg_type t on t.oid = u.x) as argudts,
    p.pronargdefaults as ndefaults, p.pronargs as nargs
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  join pg_type rt on rt.oid = p.prorettype
  where n.nspname = 'public' and rt.typname <> 'trigger' and p.prokind = 'f'
  order by p.proname`);

function tsScalar(udt, cat) {
  if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
  if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(udt)) return "number";
  if (udt === "bool") return "boolean";
  if (["json", "jsonb"].includes(udt)) return "Json";
  if (["text", "varchar", "bpchar", "uuid", "citext", "timestamptz", "timestamp", "date", "time", "interval", "inet"].includes(udt)) return "string";
  if (udt === "tsvector") return "unknown";
  if (udt === "void") return "undefined";
  if (cat === "S") return "string";
  return "unknown";
}
function tsType(col) {
  if (col.cat === "A") {
    const inner = tsScalar(col.elem_udt);
    return `${inner}[]`;
  }
  return tsScalar(col.udt, col.cat);
}
function tsFromArg(udt) {
  if (udt.startsWith("_")) return `${tsScalar(udt.slice(1))}[]`;
  return tsScalar(udt);
}

const tables = {};
for (const c of columns) (tables[c.table] ??= []).push(c);

let out = `// AUTO-GENERATED by scripts/gen-db-types.mjs from supabase/migrations — do not edit by hand.
// Regenerate with: npm run db:types

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  __InternalSupabase: { PostgrestVersion: "13.0.5" };
  public: {
    Tables: {
`;
for (const [table, cols] of Object.entries(tables)) {
  const row = cols.map((c) => `          ${c.name}: ${tsType(c)}${c.nullable ? " | null" : ""};`).join("\n");
  const ins = cols
    .map((c) => {
      if (c.is_generated) return `          ${c.name}?: never;`;
      const opt = c.nullable || c.has_default || c.is_identity;
      return `          ${c.name}${opt ? "?" : ""}: ${tsType(c)}${c.nullable ? " | null" : ""};`;
    })
    .join("\n");
  const upd = cols
    .map((c) => (c.is_generated ? `          ${c.name}?: never;` : `          ${c.name}?: ${tsType(c)}${c.nullable ? " | null" : ""};`))
    .join("\n");
  const rels = fks
    .filter((f) => f.table === table && f.ref_schema === "public")
    .map(
      (f) => `          {
            foreignKeyName: "${f.name}";
            columns: [${f.cols.map((x) => `"${x}"`).join(", ")}];
            isOneToOne: ${f.one_to_one};
            referencedRelation: "${f.ref_table}";
            referencedColumns: [${f.ref_cols.map((x) => `"${x}"`).join(", ")}];
          },`
    )
    .join("\n");
  out += `      ${table}: {
        Row: {
${row}
        };
        Insert: {
${ins}
        };
        Update: {
${upd}
        };
        Relationships: [
${rels}
        ];
      };
`;
}
out += `    };
    Views: { [_ in never]: never };
    Functions: {
`;
for (const f of functions) {
  const inputs = [];
  const outputs = [];
  const n = f.argtypes?.length ?? 0;
  for (let i = 0; i < n; i++) {
    const mode = f.argmodes[i] ?? "i";
    const entry = { name: f.argnames[i] || `arg${i}`, udt: f.argudts[i] };
    if (mode === "i" || mode === "b") inputs.push(entry);
    if (mode === "o" || mode === "t" || mode === "b") outputs.push(entry);
  }
  const firstDefault = inputs.length - f.ndefaults;
  const args = inputs.length
    ? `{ ${inputs.map((a, i) => `${a.name}${i >= firstDefault ? "?" : ""}: ${tsFromArg(a.udt)}`).join("; ")} }`
    : "never";
  let ret;
  if (outputs.length) {
    ret = `{ ${outputs.map((o) => `${o.name}: ${tsFromArg(o.udt)}`).join("; ")} }[]`;
  } else {
    ret = tsFromArg(f.ret_udt);
    if (f.retset) ret = `${ret}[]`;
  }
  out += `      ${f.name}: { Args: ${args}; Returns: ${ret} };\n`;
}
out += `    };
    Enums: {
${enums.map((e) => `      ${e.name}: ${e.labels.map((l) => `"${l}"`).join(" | ")};`).join("\n")}
    };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
export type DbFunctions = PublicSchema["Functions"];
`;

writeFileSync(new URL("../src/types/database.types.ts", import.meta.url), out);
console.log(`Wrote src/types/database.types.ts (${Object.keys(tables).length} tables, ${functions.length} functions, ${enums.length} enums)`);
await db.close();
